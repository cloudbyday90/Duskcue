use axum::{routing::get, Json, Router};
use serde_json::{json, Value};

async fn health_check() -> Json<Value> {
    Json(json!({ "status": "ok" }))
}

pub fn build_router() -> Router {
    Router::new().route("/health", get(health_check))
}
