use std::path::Path;

pub(super) fn build(directory: &Path) -> Vec<String> {
    let mut args: Vec<String> = [
        "-nostdin",
        "-hide_banner",
        "-loglevel",
        "error",
        "-nostats",
        "-y",
        "-threads",
        "2",
        "-filter_threads",
        "1",
        "-filter_complex_threads",
        "1",
        "-protocol_whitelist",
        "pipe",
        "-format_whitelist",
        "mpegts",
        "-f",
        "mpegts",
        "-i",
        "pipe:0",
        "-map",
        "0:v:0",
        "-map",
        "0:a:0",
        "-sn",
        "-dn",
        "-map_metadata",
        "-1",
        "-c:v",
        "libx264",
        "-preset",
        "ultrafast",
        "-pix_fmt",
        "yuv420p",
        "-threads:v",
        "2",
        "-vf",
        "scale=640:360:force_original_aspect_ratio=decrease:force_divisible_by=2,setsar=1,fps=30",
        "-b:v",
        "1500k",
        "-maxrate",
        "1800k",
        "-bufsize",
        "3600k",
        "-g",
        "60",
        "-keyint_min",
        "60",
        "-sc_threshold",
        "0",
        "-flags",
        "+cgop",
        "-c:a",
        "aac",
        "-b:a",
        "128k",
        "-ac",
        "2",
        "-ar",
        "48000",
        "-f",
        "hls",
        "-hls_time",
        "2",
        "-hls_list_size",
        "15",
        "-hls_delete_threshold",
        "2",
        "-hls_segment_type",
        "fmp4",
        "-hls_fmp4_init_filename",
        "init.mp4",
        "-hls_flags",
        "delete_segments+temp_file+independent_segments+omit_endlist",
        "-hls_segment_filename",
    ]
    .into_iter()
    .map(str::to_string)
    .collect();
    args.push(
        directory
            .join("seg_%08d.m4s")
            .to_string_lossy()
            .into_owned(),
    );
    args.push(
        directory
            .join("manifest.m3u8")
            .to_string_lossy()
            .into_owned(),
    );
    args
}
